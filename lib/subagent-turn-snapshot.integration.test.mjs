import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { fauxAssistantMessage, fauxProvider, fauxText, fauxToolCall } from "@earendil-works/pi-ai";
import { createAgentSessionFromServices, createAgentSessionServices, ModelRuntime, SessionManager, SettingsManager } from "@earendil-works/pi-coding-agent";
import { createJiti } from "jiti";
const exec = promisify(execFile);
const answer = (text) => fauxAssistantMessage([fauxText(text)]);

test("a freshly spawned child can enable the named recorder and record live resumes without RPC reopen", { timeout: 60_000 }, async (t) => {
  const root = await mkdtemp(join(tmpdir(), "pi-web-child-recorder-"));
  const cwd = join(root, "checkout"), agentDir = join(root, "agent");
  const previousAgentDir = process.env.PI_CODING_AGENT_DIR;
  const previousRegistry = globalThis.__piSessions;
  const sessions = new Map();
  process.env.PI_CODING_AGENT_DIR = agentDir; globalThis.__piSessions = sessions;
  t.after(async () => {
    await Promise.all([...sessions.values()].map((wrapper) => wrapper.shutdown()));
    globalThis.__piSessions = previousRegistry;
    if (previousAgentDir === undefined) delete process.env.PI_CODING_AGENT_DIR; else process.env.PI_CODING_AGENT_DIR = previousAgentDir;
    await rm(root, { recursive: true, force: true });
  });
  await mkdir(cwd); await mkdir(join(agentDir, "agents"), { recursive: true });
  await writeFile(join(agentDir, "agents", "fixture.md"), ["---", "description: Exercise the child recorder with the real SDK.", "tools: write", "load_skills: false", "load_extensions: false", "---", "Complete the delegated task."].join("\n"));
  await writeFile(join(agentDir, "settings.json"), JSON.stringify({ compaction: { enabled: false }, retry: { enabled: false } }));
  const jiti = createJiti(import.meta.url, { interopDefault: true, alias: { "@": resolve(dirname(fileURLToPath(import.meta.url)), "..") } });
  const { createSubagentController } = await jiti.import("./subagent-runtime.ts");
  const { AgentSessionWrapper } = await jiti.import("./rpc-manager.ts");
  const { POST } = await jiti.import("../app/api/workbench/snapshots/route.ts");
  const { TurnSnapshotStore } = await jiti.import("./workbench/turn-snapshot-store.ts");
  const { TURN_SNAPSHOT_EXTENSION_PATH } = await jiti.import("./workbench/turn-snapshot.ts");
  const { snapshotGitEnvironment } = await jiti.import("./workbench/turn-snapshot-capture.ts");
  const git = (args) => exec("git", ["-c", "core.fsmonitor=false", ...args], { cwd, env: snapshotGitEnvironment() });
  await git(["init", "--template=", "-q"]);
  await writeFile(join(cwd, "source.txt"), "original\n"); await git(["add", "."]);
  const index = await readFile(join(cwd, ".git", "index"));
  const faux = fauxProvider({ models: [{ id: "child-recorder-model" }] });
  const modelRuntime = await ModelRuntime.create({ authPath: join(agentDir, "auth.json"), modelsPath: null, refreshOnCreate: false });
  modelRuntime.registerNativeProvider(faux.provider);
  const services = await createAgentSessionServices({ cwd, agentDir, modelRuntime, settingsManager: SettingsManager.inMemory(), resourceLoaderOptions: { noExtensions: true, noSkills: true, noPromptTemplates: true, noThemes: true, noContextFiles: true } });
  const manager = SessionManager.create(cwd, join(agentDir, "sessions"));
  manager.appendMessage({ role: "user", content: "Saved parent fixture", timestamp: Date.now() }); manager.appendMessage(answer("Saved parent answer"));
  const { session: parent } = await createAgentSessionFromServices({ services, sessionManager: manager, model: faux.getModel("child-recorder-model") });
  const registerSession = (inner, options) => {
    const wrapper = new AgentSessionWrapper(inner, { ...options, suppressCompletionNotifications: true }); sessions.set(inner.sessionId, wrapper); wrapper.start();
    if (!wrapper.isChatOnly()) wrapper.beginExtensionBinding(); return wrapper;
  };
  registerSession(parent);
  let reopenCalls = 0;
  const { extensionRuntime: runtime } = createSubagentController({ getSession: (id) => sessions.get(id), registerSession, resolveSessionPath: async (id) => sessions.get(id)?.sessionFile ?? null, reopenSession: async () => { reopenCalls++; throw new Error("The test must retain the freshly spawned child runtime"); }, invalidateSessionList() {}, isBuiltInSubagentsEnabled: () => true });
  const request = { parentContext: { sessionManager: manager }, parentToolCallId: "child-recorder-call", profile: "fixture", task: "Report readiness", description: "Child recorder fixture", runInBackground: false };
  faux.setResponses([answer("READY")]);
  const first = await (await runtime.start(request)).completion;
  assert.equal(first.status, "completed"); assert.equal(first.result, "READY");
  const child = sessions.get(first.sessionId); await child.waitUntilReady();
  assert.ok(child.inner.resourceLoader.getExtensions().extensions.some((extension) => extension.path === TURN_SNAPSHOT_EXTENSION_PATH));
  const store = new TurnSnapshotStore(agentDir); assert.deepEqual(await store.list(first.sessionId), { enabled: false, snapshots: [] });
  const enabled = await POST(new Request("http://localhost/api/workbench/snapshots", { method: "POST", headers: { host: "localhost", "content-type": "application/json" }, body: JSON.stringify({ sessionId: first.sessionId, action: "set-enabled", enabled: true }) }));
  assert.equal(enabled.status, 200); assert.deepEqual(await enabled.json(), { enabled: true, snapshots: [] });
  const results = [first];
  for (const content of ["first recorded resume\n", "second recorded resume\n"]) {
    faux.setResponses([async () => {
      const state = JSON.parse(await readFile(join(store.directory, "state.json"), "utf8"));
      const active = state.records.find((record) => record.sessionId === first.sessionId && record.status === "open"); assert.ok(active); assert.equal(active.before.state, "complete");
      return fauxAssistantMessage([fauxToolCall("write", { path: "source.txt", content })], { stopReason: "toolUse" });
    }, answer("RECORDED")]);
    const result = await (await runtime.resume({ ...request, sessionId: first.sessionId, task: `Write ${content.trim()}` })).completion;
    assert.equal(result.status, "completed", result.error); assert.equal(result.result, "RECORDED"); assert.equal(sessions.get(result.sessionId), child);
    assert.ok(result.resultEntryId); assert.equal(child.inner.sessionManager.getEntry(result.resultEntryId).customType, "pi-web:subagent-result"); results.push(result);
  }
  assert.equal(new Set(results.map((result) => result.resultEntryId)).size, 3); assert.equal(reopenCalls, 0);
  const listing = await store.list(first.sessionId); assert.equal(listing.enabled, true); assert.equal(listing.snapshots.length, 2);
  const details = await Promise.all(listing.snapshots.map((snapshot) => store.detail(first.sessionId, snapshot.snapshotId)));
  assert.ok(details.every((detail) => detail.status === "completed" && detail.coverage.state === "complete"));
  assert.deepEqual(details.flatMap((detail) => detail.files).sort((a, b) => a.after.localeCompare(b.after)), [{ path: "source.txt", kind: "modified", before: "original\n", after: "first recorded resume\n" }, { path: "source.txt", kind: "modified", before: "first recorded resume\n", after: "second recorded resume\n" }]);
  assert.deepEqual(await store.list(parent.sessionId), { enabled: false, snapshots: [] }); assert.deepEqual(await readFile(join(cwd, ".git", "index")), index);
});
