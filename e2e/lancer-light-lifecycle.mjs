import assert from 'node:assert/strict';
import {mkdirSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {chromium} from 'playwright';
const base=process.env.LANCER_TEST_BASE??'http://127.0.0.1:30143';
const out=resolve(process.env.LANCER_TEST_ARTIFACTS??'artifacts/lancer-light-fidelity');mkdirSync(out,{recursive:true});
const id='remote-motion-parent';
const session={id,name:'Live graph fixture',cwd:'D:/coding/pi-web-c',created:'2026-11-03T00:00:00Z',modified:'2026-11-03T00:00:00Z'};
const node=entry=>({id:id+':'+entry,entryId:entry,sessionId:id,parentId:null,kind:'answer',text:'Recorded '+entry,timestamp:session.created});
let graph={sessionId:id,running:[],truncated:false,edges:[],lanes:[{session,model:'fixture/primary',truncated:false,nodes:Array.from({length:35},(_,i)=>node('history-'+i))}]};
let holdNext=null,requests=0,modelRequests=0;const errors=[];
