 assert.equal(await page.locator('[data-task-node]').count(),35);
 assert.equal(await target.evaluate(el=>document.activeElement===el),true);
 assert.equal(await page.locator('.lancer-tree-scroll').evaluate(el=>el.scrollTop),initialScroll);
 const beforeBurst=requests;
 for(let i=0;i<4;i++)await page.getByRole('button',{name:'Refresh graph',exact:true}).evaluate(el=>el.click());
 assert.equal(requests,beforeBurst,'in-flight refreshes must coalesce');
 refreshGate.release();
 await page.waitForFunction(()=>!document.querySelector('.lancer-tree [role=status]'));
 await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
 assert.equal(await target.evaluate(el=>document.activeElement===el),true);
 assert.equal(await page.locator('.lancer-tree-scroll').evaluate(el=>el.scrollTop),initialScroll);
 report.checks.push('refresh-retains-node-dom-scroll-and-focus','event-refreshes-coalesce');
 graph={...graph,lanes:[{...graph.lanes[0],nodes:[...graph.lanes[0].nodes,node('late-entry')]}]};
 await page.getByRole('button',{name:'Refresh graph',exact:true}).click();
 const model=page.locator('[data-curve-id="'+id+':late-entry:model"]');const message=page.locator('[data-curve-id="'+id+':late-entry:message"]');
 await model.waitFor({state:'attached'});assert.equal(await message.count(),0);
 await model.waitFor({state:'detached',timeout:4000});
 await page.getByRole('button',{name:'Attach canonical ID',exact:true}).click();await message.waitFor({state:'attached'});
