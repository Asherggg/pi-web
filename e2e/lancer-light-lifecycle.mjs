 const openGate=gate();holdNext=openGate;await page.getByRole('button',{name:'Toggle tree',exact:true}).click();await openGate.started;
 assert.equal(await page.locator('[data-task-node]').count(),0,'reopen must not reuse the previous generation');
 openGate.release();await page.locator('[data-task-node="'+id+':recorded-while-closed"]').waitFor({state:'attached'});
