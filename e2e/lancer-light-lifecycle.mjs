 await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
 assert.equal(await message.count(),0,'nested clipping must cancel the in-flight message');
 assert.equal(await model.count(),0,'the earlier model source must remain completed');
 report.checks.push('nested-clipping-is-rechecked-during-flight');
 await page.getByRole('button',{name:'Toggle tree',exact:true}).click();await page.waitForFunction(()=>!document.querySelector('[data-light-layer]'));
